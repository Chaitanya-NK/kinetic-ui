#!/usr/bin/env node
/**
 * Builds the Figma plugin that generates the Kinetic UI kit.
 * Reads design tokens from packages/core/styles.css and icon paths from @kineticui/icons, so the kit
 * always matches the code, then bundles figma/src/code.ts into figma/code.js.
 *
 *   node figma/build.mjs        (run `npm run build:packages` first for the icons)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import { deflateRawSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const css = readFileSync(join(root, "packages/core/styles.css"), "utf8");
const version = JSON.parse(readFileSync(join(root, "packages/ui/package.json"), "utf8")).version;

/** Every --kn-* custom property in the first block that starts with `selector`. */
function block(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`No ${selector} block in styles.css`);
  const open = css.indexOf("{", start);
  const close = css.indexOf("}", open);
  const out = {};
  for (const m of css.slice(open + 1, close).matchAll(/--kn-([a-z-]+):\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

const dark = block(":root,\n.dark");
const light = block(".light {");
const missing = Object.keys(dark).filter((k) => !(k in light));
if (missing.length) console.warn(`! Light theme has no value for: ${missing.join(", ")} (dark value used)`);

const { iconPaths } = await import(pathToFileURL(join(root, "packages/icons/dist/index.js")).href);

const data = `// Generated by figma/build.mjs from packages/core/styles.css and @kineticui/icons. Do not edit.
export const version = ${JSON.stringify(version)};
export const tokens = ${JSON.stringify({ dark, light: { ...dark, ...light } }, null, 2)} as const;
export const icons: Record<string, string> = ${JSON.stringify(iconPaths)};
`;
writeFileSync(join(here, "src/data.generated.ts"), data);

await build({
  entryPoints: [join(here, "src/code.ts")],
  outfile: join(here, "code.js"),
  bundle: true,
  format: "iife",
  target: "es2019",
  logLevel: "warning",
  banner: { js: `// Kinetic UI kit for Figma v${version}. Built by figma/build.mjs; edit figma/src/code.ts instead.` },
});

/* Zip manifest.json + code.js for download from the docs site (no dependencies). */
const crcTable = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
function zip(entries) {
  const locals = [], centrals = [];
  let offset = 0;
  for (const [name, data] of entries) {
    const comp = deflateRawSync(data), nameBuf = Buffer.from(name), crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6); local.writeUInt16LE(8, 8);
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(nameBuf.length, 26);
    locals.push(local, nameBuf, comp);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10);
    central.writeUInt32LE(crc, 16); central.writeUInt32LE(comp.length, 20); central.writeUInt32LE(data.length, 24); central.writeUInt16LE(nameBuf.length, 28); central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += 30 + nameBuf.length + comp.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}
writeFileSync(
  join(root, "apps/docs/public/kinetic-ui-figma-kit.zip"),
  zip(["manifest.json", "code.js", "README.md"].map((f) => [`kinetic-ui-figma-kit/${f}`, readFileSync(join(here, f))])),
);

console.log(`✓ Figma plugin: ${Object.keys(dark).length} colour tokens, ${Object.keys(iconPaths).length} icons → figma/code.js`);
