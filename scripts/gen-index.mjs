#!/usr/bin/env node
/** Regenerates the barrel files so every component file is exported. Run before building. */
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const targets = [
  { dir: "packages/ui/src/components", out: "packages/ui/src/index.ts", prefix: "./components/" },
  { dir: "packages/motion/src", out: "packages/motion/src/index.ts", prefix: "./" },
  { dir: "packages/blocks/src/blocks", out: "packages/blocks/src/index.ts", prefix: "./blocks/" },
];

for (const t of targets) {
  let files;
  try {
    files = readdirSync(join(root, t.dir)).filter((f) => f.endsWith(".tsx")).sort();
  } catch {
    continue;
  }
  const body = files.map((f) => `export * from "${t.prefix}${f.replace(/\.tsx$/, "")}";`).join("\n");
  writeFileSync(join(root, t.out), `// Generated by scripts/gen-index.mjs — do not edit by hand.\n${body}\n`);
  console.log(`✓ ${t.out} (${files.length} files)`);
}
